/// Generates a random name from the list of adjectives and animals in this crate
/// formatted as "adjective-animal-{3-digit-random-number}".
pub fn get_random(mut rng: impl rand_core::Rng) -> String {
    let num = rng.next_u64() % 1000;
    let adj = ADJECTIVES[(rng.next_u64() % ADJECTIVES.len() as u64) as usize];
    let animal = ANIMALS[(rng.next_u64() % ANIMALS.len() as u64) as usize];

    format!("{adj}-{animal}-{:03}", num)
}

#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use rand::rng;

    use super::*;

    #[test]
    fn test_ends_with_three_digit_num() {
        let mut rng = rng();
        let name = get_random(&mut rng);

        assert_eq!(name.split('-').count(), 3);
        assert_eq!(name.split('-').next_back().unwrap().len(), 3);
    }

    #[test]
    fn test_at_least_400_million_combinations() {
        let combinations = ADJECTIVES.len() * ANIMALS.len() * 1000;
        assert!(
            combinations >= 400_000_000,
            "only {combinations} combinations"
        );
    }

    #[test]
    fn test_words_are_unique_lowercase_letters() {
        for list in [ADJECTIVES, ANIMALS] {
            assert_eq!(list.iter().collect::<HashSet<_>>().len(), list.len());
            assert!(
                list.iter()
                    .all(|w| !w.is_empty() && w.bytes().all(|b| b.is_ascii_lowercase()))
            );
        }
    }
}
